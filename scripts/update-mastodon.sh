#!/usr/bin/env bash
# Regenerates mastodon/ for a Mastodon tag, by default the latest patch
# release of the pinned major.minor (minor bumps must be explicit). Like
# nixpkgs' update.sh, but against the flake's nixpkgs (NIXPKGS_PATH, set by
# the flake wrapper). Run via `nix run .#update-mastodon`.
set -euo pipefail

if [[ ! -f flake.nix ]]; then
  echo "error: run this from the root of the repo (flake.nix not found here)" >&2
  exit 1
fi

# bundix and friends fall back to <nixpkgs> for helper evaluations.
export NIX_PATH="nixpkgs=$NIXPKGS_PATH"

fake_hash="sha256-AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA="

usage="usage: nix run .#update-mastodon -- [--force] [vX.Y.Z]"
force=false
tag=""
for arg in "$@"; do
  case "$arg" in
    --force) force=true ;;
    -h | --help) echo "$usage" >&2; exit 0 ;;
    -*) echo "$usage" >&2; exit 1 ;;
    *) tag="$arg" ;;
  esac
done

current=$(sed -n 's/^  version = "\(.*\)";$/\1/p' mastodon/source.nix 2>/dev/null || true)

github_api() {
  curl -sf ${GITHUB_TOKEN:+-H "Authorization: Bearer $GITHUB_TOKEN"} "https://api.github.com/repos/mastodon/mastodon/$1"
}

explicit=true
if [[ -z "$tag" ]]; then
  explicit=false
  if [[ "$current" =~ ^([0-9]+\.[0-9]+)\.[0-9]+$ ]]; then
    series="${BASH_REMATCH[1]}"
    echo "Resolving latest stable $series.x release..." >&2
    tag=$(github_api "releases?per_page=100" |
      jq -r --arg prefix "v$series." \
        '.[] | select((.draft or .prerelease) | not) | .tag_name | select(startswith($prefix))' |
      grep -E "^v${series//./\\.}\.[0-9]+$" | sort -V | tail -n 1 || true)
  else
    echo "Resolving latest stable Mastodon release..." >&2
    tag=$(github_api releases/latest | jq -r '.tag_name // empty' || true)
  fi
fi
if [[ -z "$tag" || "$tag" == "null" ]]; then
  echo "error: could not resolve a Mastodon release tag (GitHub API rate limit?). Pass one explicitly: nix run .#update-mastodon -- v4.7.0" >&2
  exit 1
fi
if [[ "$tag" != v* ]]; then
  echo "error: expected a tag like v4.6.6, got '$tag'" >&2
  exit 1
fi
version="${tag#v}"
echo "Target version: $tag" >&2

# Never downgrade on our own (migrated databases don't go back).
if [[ -n "$current" && "$current" != "$version" ]] &&
  [[ "$(printf '%s\n%s\n' "$current" "$version" | sort -V | tail -n 1)" == "$current" ]]; then
  if [[ "$explicit" != true ]]; then
    echo "Resolved $tag is older than the pinned $current; leaving mastodon/ alone." >&2
    exit 0
  fi
  echo "warning: $tag is older than the pinned $current (downgrade, as explicitly requested)" >&2
fi

if [[ "$current" == "$version" && "$force" != true ]]; then
  echo "mastodon/ is already pinned to $tag; nothing to do (--force regenerates it anyway)." >&2
  exit 0
fi

# Staged next to mastodon/ and swapped in only once everything succeeded.
stage=$(mktemp -d mastodon.update.XXXXXX)
trap 'rm -rf "$stage" mastodon.old' EXIT

write_source() {
  local src_hash="$1" yarn_hash="$2"
  cat >"$stage/source.nix" <<EOF
# Generated by scripts/update-mastodon.sh (nix run .#update-mastodon) - do not edit.
{
  fetchFromGitHub,
  applyPatches,
  patches ? [ ],
}:
let
  version = "$version";
in
applyPatches {
  src = fetchFromGitHub {
    owner = "mastodon";
    repo = "mastodon";
    rev = "v\${version}";
    hash = "$src_hash";
    passthru = {
      inherit version;
      yarnHash = "$yarn_hash";
      yarnMissingHashes = ./missing-hashes.json;
    };
  };
  inherit patches;
}
EOF
}

echo "Fetching source at $tag..." >&2
src_hash=$(nix-prefetch-github mastodon mastodon --rev "$tag" | jq -r .hash)
write_source "$src_hash" "$fake_hash"
source_dir=$(nix build --impure --no-link --print-out-paths --expr \
  "(import $NIXPKGS_PATH {}).callPackage $PWD/$stage/source.nix {}")

echo "Generating gemset.nix (prefetches every gem, takes a while)..." >&2
bundix --lockfile="$source_dir/Gemfile.lock" --gemfile="$source_dir/Gemfile" \
  --gemset="$stage/gemset.nix"

echo "Resolving yarn offline cache hash..." >&2
yarn-berry-fetcher missing-hashes "$source_dir/yarn.lock" >"$stage/missing-hashes.json"
yarn_hash=$(yarn-berry-fetcher prefetch "$source_dir/yarn.lock" "$stage/missing-hashes.json" 2>/dev/null)
if [[ "$yarn_hash" != sha256-* ]]; then
  echo "error: yarn-berry-fetcher did not return a hash (got '$yarn_hash')" >&2
  exit 1
fi
write_source "$src_hash" "$yarn_hash"

chmod 0755 "$stage"
if [[ -d mastodon ]]; then mv mastodon mastodon.old; fi
mv "$stage" mastodon
rm -rf mastodon.old

echo "Updated mastodon/ to $tag." >&2
echo "Review the diff, then: nix flake check && nix build .#packages.<system>.image" >&2
